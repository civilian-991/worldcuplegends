import type { Metadata } from 'next';
import ContactContent from './ContactContent';

const siteUrl = 'https://wlc.world';

type Props = { params: Promise<{ locale: string }> };

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { locale } = await params;
  const isEn = locale === 'en';
  const path = '/contact';
  const title = isEn ? 'Contact Us - World Legends Cup 2026' : 'Fale Conosco - Copa das Lendas 2026';
  const description = isEn
    ? 'Get in touch with the World Legends Cup 2026 team for inquiries, partnerships, and support.'
    : 'Entre em contato com a equipe da Copa das Lendas 2026 para dúvidas, parcerias e suporte.';

  return {
    title,
    description,
    alternates: {
      canonical: `${siteUrl}/${locale}${path}`,
      languages: {
        en: `${siteUrl}/en${path}`,
        'pt-BR': `${siteUrl}/br${path}`,
        'x-default': `${siteUrl}/en${path}`,
      },
    },
    openGraph: {
      title,
      description,
      url: `${siteUrl}/${locale}${path}`,
      siteName: 'World Legends Cup',
      images: [{ url: `${siteUrl}/og-image.png`, width: 1200, height: 630, alt: 'World Legends Cup 2026' }],
      locale: isEn ? 'en_US' : 'pt_BR',
      type: 'website',
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description,
      images: [`${siteUrl}/og-image.png`],
    },
  };
}

export default function ContactPage() {
  return <ContactContent />;
}
